package com.jc.hospital;

import java.sql.Connection;
import java.sql.Date;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.function.Function;

import javafx.application.Application;
import javafx.beans.property.ReadOnlyObjectWrapper;
import javafx.collections.FXCollections;
import javafx.collections.ObservableList;
import javafx.geometry.Insets;
import javafx.geometry.Pos;
import javafx.scene.Scene;
import javafx.scene.control.Alert;
import javafx.scene.control.Button;
import javafx.scene.control.ButtonType;
import javafx.scene.control.ComboBox;
import javafx.scene.control.DateCell;
import javafx.scene.control.DatePicker;
import javafx.scene.control.Label;
import javafx.scene.control.TableColumn;
import javafx.scene.control.TableView;
import javafx.scene.control.TextField;
import javafx.scene.layout.BorderPane;
import javafx.scene.layout.GridPane;
import javafx.scene.layout.HBox;
import javafx.scene.layout.Priority;
import javafx.scene.layout.VBox;
import javafx.stage.Stage;

/** Hospital Management System - patient registration Lab 6. */
public class HospitalApp extends Application {

	/** One row of the patients table. */
	private record Patient(int patientId, String name, int age, String gender,
			String phone, String diagnosis, LocalDate admissionDate) {
	}

	private final ObservableList<Patient> patients = FXCollections.observableArrayList();

	// Form controls
	private final TextField idField = new TextField();
	private final TextField nameField = new TextField();
	private final TextField ageField = new TextField();
	private final ComboBox<String> genderBox = new ComboBox<>();
	private final TextField phoneField = new TextField();
	private final TextField diagnosisField = new TextField();
	private final DatePicker admissionPicker = new DatePicker();

	// Records area
	private final TextField searchField = new TextField();
	private final TableView<Patient> table = new TableView<>();

	// Status bar
	private final Label statusLabel = new Label("Ready.");

	@Override
	public void start(Stage stage) {
		BorderPane root = new BorderPane();
		root.setTop(buildTop());
		root.setCenter(buildCenter());
		root.setBottom(buildBottom());

		stage.setTitle("Hospital Management System - Patient Registration");
		stage.setScene(new Scene(root, 1150, 600));
		stage.show();

		loadAll();
	}

	//  UI building

	private VBox buildTop() {
		Label title = new Label("Hospital Management System");
		title.setStyle("-fx-font-size: 22px; -fx-font-weight: bold;");
		Label subtitle = new Label("Patient Registration - fictional data only");
		VBox top = new VBox(4, title, subtitle);
		top.setPadding(new Insets(12, 15, 8, 15));
		return top;
	}

	private HBox buildCenter() {
		VBox formBox = buildFormBox();
		VBox recordsBox = buildRecordsBox();
		HBox.setHgrow(recordsBox, Priority.ALWAYS);
		HBox center = new HBox(20, formBox, recordsBox);
		center.setPadding(new Insets(10, 15, 10, 15));
		return center;
	}

	private VBox buildFormBox() {
		idField.setEditable(false);
		idField.setPromptText("Generated by database");
		genderBox.getItems().addAll("Female", "Male", "Non-binary", "Prefer not to say");
		genderBox.setPromptText("Select");
		genderBox.setMaxWidth(Double.MAX_VALUE);
		// a future admission date cannot be picked
		admissionPicker.setDayCellFactory(picker -> new DateCell() {
			@Override
			public void updateItem(LocalDate date, boolean empty) {
				super.updateItem(date, empty);
				setDisable(empty || date.isAfter(LocalDate.now()));
			}
		});

		GridPane grid = new GridPane();
		grid.setHgap(10);
		grid.setVgap(10);
		grid.addRow(0, new Label("Patient ID"), idField);
		grid.addRow(1, new Label("Full name"), nameField);
		grid.addRow(2, new Label("Age"), ageField);
		grid.addRow(3, new Label("Gender"), genderBox);
		grid.addRow(4, new Label("Phone"), phoneField);
		grid.addRow(5, new Label("Diagnosis / reason"), diagnosisField);
		grid.addRow(6, new Label("Admission date"), admissionPicker);

		Button addBtn = new Button("Add Patient");
		Button updateBtn = new Button("Update");
		Button deleteBtn = new Button("Delete");
		Button clearBtn = new Button("Clear");
		addBtn.setOnAction(e -> addPatient());
		updateBtn.setOnAction(e -> updateSelectedPatient());
		deleteBtn.setOnAction(e -> deleteSelectedPatient());
		clearBtn.setOnAction(e -> clearForm());
		HBox buttons = new HBox(8, addBtn, updateBtn, deleteBtn, clearBtn);

		Label header = new Label("Patient Details");
		header.setStyle("-fx-font-size: 16px; -fx-font-weight: bold;");
		VBox box = new VBox(12, header, grid, buttons);
		box.setPrefWidth(380);
		return box;
	}

	private VBox buildRecordsBox() {
		searchField.setPromptText("Search by name or phone");
		HBox.setHgrow(searchField, Priority.ALWAYS);
		Button searchBtn = new Button("Search");
		Button showAllBtn = new Button("Show All");
		searchBtn.setOnAction(e -> searchPatientsAction());
		showAllBtn.setOnAction(e -> {
			searchField.clear();
			loadAll();
		});
		HBox searchRow = new HBox(8, searchField, searchBtn, showAllBtn);
		searchRow.setAlignment(Pos.CENTER_LEFT);

		table.getColumns().add(column("ID", 45, Patient::patientId));
		table.getColumns().add(column("Name", 130, Patient::name));
		table.getColumns().add(column("Age", 45, Patient::age));
		table.getColumns().add(column("Gender", 90, Patient::gender));
		table.getColumns().add(column("Phone", 110, Patient::phone));
		table.getColumns().add(column("Diagnosis", 170, Patient::diagnosis));
		table.getColumns().add(column("Admission", 95, Patient::admissionDate));
		table.setItems(patients);
		table.getSelectionModel().selectedItemProperty().addListener((obs, oldP, newP) -> {
			if (newP != null) {
				populateForm(newP);
			}
		});
		VBox.setVgrow(table, Priority.ALWAYS);

		Label header = new Label("Patient Records");
		header.setStyle("-fx-font-size: 16px; -fx-font-weight: bold;");
		return new VBox(10, header, searchRow, table);
	}

	private HBox buildBottom() {
		HBox bottom = new HBox(statusLabel);
		bottom.setPadding(new Insets(8, 15, 10, 15));
		return bottom;
	}

	private TableColumn<Patient, Object> column(String title, double width, Function<Patient, Object> getter) {
		TableColumn<Patient, Object> col = new TableColumn<>(title);
		col.setCellValueFactory(cell -> new ReadOnlyObjectWrapper<>(getter.apply(cell.getValue())));
		col.setPrefWidth(width);
		return col;
	}

	//  button handlers

	private void addPatient() {
		Patient p = readValidatedForm(0);
		if (p == null) {
			return;
		}
		try {
			insertPatient(p);
			loadAll();
			clearForm();
			setStatus("Patient '" + p.name() + "' added.", false);
		} catch (SQLException ex) {
			setStatus("Database error while adding: " + ex.getMessage(), true);
		}
	}

	private void loadAll() {
		try {
			List<Patient> list = selectAllPatients();
			patients.setAll(list);
			setStatus(list.size() + " patient record(s) loaded.", false);
		} catch (SQLException ex) {
			setStatus("Database error while loading: " + ex.getMessage(), true);
		}
	}

	private void updateSelectedPatient() {
		Patient selected = table.getSelectionModel().getSelectedItem();
		if (selected == null) {
			setStatus("Select a patient in the table first.", true);
			return;
		}
		Patient p = readValidatedForm(selected.patientId());
		if (p == null) {
			return;
		}
		try {
			int rows = updatePatient(p);
			loadAll();
			clearForm();
			setStatus(rows + " record updated (ID " + p.patientId() + ").", false);
		} catch (SQLException ex) {
			setStatus("Database error while updating: " + ex.getMessage(), true);
		}
	}

	private void deleteSelectedPatient() {
		Patient selected = table.getSelectionModel().getSelectedItem();
		if (selected == null) {
			setStatus("Select a patient in the table first.", true);
			return;
		}
		Alert confirm = new Alert(Alert.AlertType.CONFIRMATION,
				"Delete patient '" + selected.name() + "' (ID " + selected.patientId() + ")?",
				ButtonType.YES, ButtonType.NO);
		confirm.setHeaderText("Confirm delete");
		Optional<ButtonType> answer = confirm.showAndWait();
		if (answer.isEmpty() || answer.get() != ButtonType.YES) {
			setStatus("Delete cancelled.", false);
			return;
		}
		try {
			deletePatient(selected.patientId());
			loadAll();
			clearForm();
			setStatus("Patient ID " + selected.patientId() + " deleted.", false);
		} catch (SQLException ex) {
			setStatus("Database error while deleting: " + ex.getMessage(), true);
		}
	}

	private void searchPatientsAction() {
		String text = searchField.getText().trim();
		if (text.isEmpty()) {
			setStatus("Type a name or phone to search.", true);
			return;
		}
		try {
			List<Patient> list = searchPatients(text);
			patients.setAll(list);
			setStatus(list.size() + " match(es) for '" + text + "'.", false);
		} catch (SQLException ex) {
			setStatus("Database error while searching: " + ex.getMessage(), true);
		}
	}

	// validation + form

	/** Returns a Patient built from the form, or null (after showing an error) if invalid. */
	private Patient readValidatedForm(int patientId) {
		String name = nameField.getText().trim();
		String ageText = ageField.getText().trim();
		String gender = genderBox.getValue();
		String phone = phoneField.getText().trim();
		String diagnosis = diagnosisField.getText().trim();
		LocalDate date = admissionPicker.getValue();

		if (name.isEmpty() || ageText.isEmpty() || gender == null
				|| phone.isEmpty() || diagnosis.isEmpty() || date == null) {
			setStatus("All fields are required.", true);
			return null;
		}
		int age;
		try {
			age = Integer.parseInt(ageText);
		} catch (NumberFormatException ex) {
			setStatus("Age must be a whole number.", true);
			return null;
		}
		if (age < 0 || age > 125) {
			setStatus("Age must be between 0 and 125.", true);
			return null;
		}
		if (!phone.matches("[0-9+()\\- ]{7,20}")) {
			setStatus("Phone must have 7-20 characters: digits, spaces, + ( ) -", true);
			return null;
		}
		if (date.isAfter(LocalDate.now())) {
			setStatus("Admission date cannot be in the future.", true);
			return null;
		}
		return new Patient(patientId, name, age, gender, phone, diagnosis, date);
	}

	private void populateForm(Patient p) {
		idField.setText(String.valueOf(p.patientId()));
		nameField.setText(p.name());
		ageField.setText(String.valueOf(p.age()));
		genderBox.setValue(p.gender());
		phoneField.setText(p.phone());
		diagnosisField.setText(p.diagnosis());
		admissionPicker.setValue(p.admissionDate());
	}

	private void clearForm() {
		idField.clear();
		nameField.clear();
		ageField.clear();
		genderBox.setValue(null);
		phoneField.clear();
		diagnosisField.clear();
		admissionPicker.setValue(null);
		table.getSelectionModel().clearSelection();
	}

	private void setStatus(String message, boolean error) {
		statusLabel.setText(message);
		statusLabel.setStyle(error ? "-fx-text-fill: #b00020;" : "-fx-text-fill: #167545;");
	}

	// database (JDBC)

	/** CREATE */
	private int insertPatient(Patient p) throws SQLException {
		String sql = "INSERT INTO patients (name, age, gender, phone, diagnosis, admission_date) "
				+ "VALUES (?, ?, ?, ?, ?, ?)";
		try (Connection con = DBConnection.getConnection();
				PreparedStatement ps = con.prepareStatement(sql)) {
			ps.setString(1, p.name());
			ps.setInt(2, p.age());
			ps.setString(3, p.gender());
			ps.setString(4, p.phone());
			ps.setString(5, p.diagnosis());
			ps.setDate(6, Date.valueOf(p.admissionDate()));
			return ps.executeUpdate();
		}
	}

	/** READ (all rows) */
	private List<Patient> selectAllPatients() throws SQLException {
		String sql = "SELECT patient_id, name, age, gender, phone, diagnosis, admission_date "
				+ "FROM patients ORDER BY patient_id";
		List<Patient> list = new ArrayList<>();
		try (Connection con = DBConnection.getConnection();
				PreparedStatement ps = con.prepareStatement(sql);
				ResultSet rs = ps.executeQuery()) {
			while (rs.next()) {
				list.add(mapRow(rs));
			}
		}
		return list;
	}

	/** SEARCH by name or phone */
	private List<Patient> searchPatients(String text) throws SQLException {
		String sql = "SELECT patient_id, name, age, gender, phone, diagnosis, admission_date "
				+ "FROM patients WHERE name LIKE ? OR phone LIKE ? ORDER BY patient_id";
		String pattern = "%" + text + "%";
		List<Patient> list = new ArrayList<>();
		try (Connection con = DBConnection.getConnection();
				PreparedStatement ps = con.prepareStatement(sql)) {
			ps.setString(1, pattern);
			ps.setString(2, pattern);
			try (ResultSet rs = ps.executeQuery()) {
				while (rs.next()) {
					list.add(mapRow(rs));
				}
			}
		}
		return list;
	}

	/** UPDATE using the selected patient_id */
	private int updatePatient(Patient p) throws SQLException {
		String sql = "UPDATE patients SET name = ?, age = ?, gender = ?, phone = ?, diagnosis = ?, "
				+ "admission_date = ? WHERE patient_id = ?";
		try (Connection con = DBConnection.getConnection();
				PreparedStatement ps = con.prepareStatement(sql)) {
			ps.setString(1, p.name());
			ps.setInt(2, p.age());
			ps.setString(3, p.gender());
			ps.setString(4, p.phone());
			ps.setString(5, p.diagnosis());
			ps.setDate(6, Date.valueOf(p.admissionDate()));
			ps.setInt(7, p.patientId());
			return ps.executeUpdate();
		}
	}

	/** DELETE using patient_id */
	private int deletePatient(int patientId) throws SQLException {
		String sql = "DELETE FROM patients WHERE patient_id = ?";
		try (Connection con = DBConnection.getConnection();
				PreparedStatement ps = con.prepareStatement(sql)) {
			ps.setInt(1, patientId);
			return ps.executeUpdate();
		}
	}

	private Patient mapRow(ResultSet rs) throws SQLException {
		return new Patient(
				rs.getInt("patient_id"),
				rs.getString("name"),
				rs.getInt("age"),
				rs.getString("gender"),
				rs.getString("phone"),
				rs.getString("diagnosis"),
				rs.getDate("admission_date").toLocalDate());
	}

	public static void main(String[] args) {
		launch(args);
	}
}
